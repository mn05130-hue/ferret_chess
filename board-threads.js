const BOARD_COMMENTER_NAMES = [
  "저녁산책", "콩국수파", "모서리", "등불하나", "감자전", "먼지구름",
  "느린우체통", "연필깎이", "누룽지", "밤신호", "빗소리", "동그라미"
];

function selectNormalBoardThread(seed, ordinal) {
  const cycle = Math.floor(ordinal / BOARD_THREADS.length);
  const order = shuffle(BOARD_THREADS, createRoundRandom(hashText(`${seed}:threads:${cycle}`)));
  const [title, body, comments] = order[ordinal % BOARD_THREADS.length];
  return { title, body, comments };
}

function createBoardComments(entries, authorName, random) {
  const names = shuffle(BOARD_COMMENTER_NAMES.filter(name => name !== authorName), random);
  let index = 0;
  return entries.map(entry => typeof entry === "string"
    ? { nickname: names[index++], body: entry }
    : { nickname: authorName, body: entry.reply, authorReply: true });
}

function renderBoardComments(list, post, disconnected = false) {
  list.replaceChildren();
  for (const comment of post.comments) {
    const item = document.createElement("li");
    if (comment.authorReply) item.classList.add("board-comment-reply");
    const author = document.createElement("strong");
    author.textContent = comment.authorReply ? `${comment.nickname} · 글쓴이` : comment.nickname;
    const body = document.createElement("p");
    body.textContent = disconnected ? createUnknownChatText(comment.body, post.author) : comment.body;
    item.append(author, body);
    list.append(item);
  }
}
